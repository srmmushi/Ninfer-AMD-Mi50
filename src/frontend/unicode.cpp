uint32_t utf8_decode(const std::string& s, size_t& pos) {
  if (pos >= s.size()) return 0xFFFD;
  const unsigned char c0 = static_cast<unsigned char>(s[pos]);
  if (c0 < 0x80) { ++pos; return c0; }
  auto cont = [&](size_t off, uint32_t& out) -> bool {
    if (pos + off >= s.size()) return false;
    unsigned char c = static_cast<unsigned char>(s[pos + off]);
    if ((c & 0xC0) != 0x80) return false;
    out = c & 0x3F;
    return true;
  };
  uint32_t cp = 0xFFFD;
  if ((c0 & 0xE0) == 0xC0) {
    uint32_t a, b;
    if (cont(1, a)) { cp = ((c0 & 0x1F) << 6) | a; pos += 2; return cp; }
  } else if ((c0 & 0xF0) == 0xE0) {
    uint32_t a, b, c;
    if (cont(1, a) && cont(2, b)) {
      cp = ((c0 & 0x0F) << 12) | (a << 6) | b;
      pos += 3;
      return cp;
    }
  } else if ((c0 & 0xF8) == 0xF0) {
    uint32_t a, b, c, d;
    if (cont(1, a) && cont(2, b) && cont(3, c)) {
      cp = ((c0 & 0x07) << 18) | (a << 12) | (b << 6) | c;
      pos += 4;
      return cp;
    }
  }
  ++pos;  // invalid byte
  return cp;
}

void utf8_encode(uint32_t cp, std::string& out) {
  if (cp < 0x80) {
    out.push_back(static_cast<char>(cp));
  } else if (cp < 0x800) {
    out.push_back(static_cast<char>(0xC0 | (cp >> 6)));
    out.push_back(static_cast<char>(0x80 | (cp & 0x3F)));
  } else if (cp < 0x10000) {
    out.push_back(static_cast<char>(0xE0 | (cp >> 12)));
    out.push_back(static_cast<char>(0x80 | ((cp >> 6) & 0x3F)));
    out.push_back(static_cast<char>(0x80 | (cp & 0x3F)));
  } else {
    out.push_back(static_cast<char>(0xF0 | (cp >> 18)));
    out.push_back(static_cast<char>(0x80 | ((cp >> 12) & 0x3F)));
    out.push_back(static_cast<char>(0x80 | ((cp >> 6) & 0x3F)));
    out.push_back(static_cast<char>(0x80 | (cp & 0x3F)));
  }
}

